// Палитры четырёх периодов.
//
// Палитра здесь — не набор красивых цветов, а цитата конкретных холстов
// и позиция. Поэтому у каждой записан источник и то, что она означает
// внутри работы, растущей из данных тела.
//
// Отдельная оговорка по канону: основная линия Symbiotic Art остаётся
// grayscale (R=G=B). Цвет живёт только в этой серии и работает как
// цитирование — заимствованная палитра мёртвого художника, наложенная
// на живые данные, сама является высказыванием.

import { clamp, lerp } from './rng';

const rampAt = (stops, t) => {
    const x = clamp(t, 0, 1) * (stops.length - 1);
    const i = Math.min(stops.length - 2, Math.floor(x));
    const f = x - i;
    const a = stops[i];
    const b = stops[i + 1];
    return [lerp(a[0], b[0], f), lerp(a[1], b[1], f), lerp(a[2], b[2], f)];
};

