/**
 * Разрешение палитры для дня. Температурное отклонение сдвигает
 * цветовую температуру: земля ↔ кобальт. Сдвиг маленький и не выводит
 * палитру за пределы цитируемых холстов — иначе цитата перестанет читаться.
 */
export const resolvePalette = (paletteId, metrics) => {
    const base = PALETTES[paletteId];
    const shift = (metrics.norm.temperature - 0.5) * 0.22;
    const warm = (rgb) => [
        clamp(rgb[0] * (1 + shift * 0.55), 0, 255),
        clamp(rgb[1] * (1 + shift * 0.12), 0, 255),
        clamp(rgb[2] * (1 - shift * 0.5), 0, 255)
    ];
    return {
        ...base,
        ground: warm(base.ground),
        sky: base.sky.map(warm),
        earth: base.earth.map(warm),
        accent: base.accent.map(warm)
    };
};

export const skyColor = (palette, t) => rampAt(palette.sky, t);
export const earthColor = (palette, t) => rampAt(palette.earth, t);
export const accentColor = (palette, t) => rampAt(palette.accent, t);

export const toCss = (rgb) =>
    `rgb(${Math.round(clamp(rgb[0], 0, 255))},${Math.round(clamp(rgb[1], 0, 255))},${Math.round(
        clamp(rgb[2], 0, 255)
    )})`;
