// Детерминизм — не техническая деталь, а условие существования работы.
// Правило + данные дня всегда дают одно и то же полотно, иначе работу
// нельзя продать по модели «сертификат + правило» (LeWitt / Gonzalez-Torres).
//
// Во всём модуле art/ не должно быть ни одного Math.random().
// Всякая «случайность» здесь — детерминированная функция от данных дня.

// FNV-1a, 32 бита. Строка (день, имя слоя) → семя.
export const hashString = (str) => {
    let h = 0x811c9dc5;
    for (let i = 0; i < str.length; i++) {
        h ^= str.charCodeAt(i);
        h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h >>> 0;
};

// Смешивание координат в стабильное псевдослучайное 32-битное число.
// Используется, чтобы разложить распределение дневного ряда по плоскости:
// позиция берётся из хэша, значение — из данных.
export const hash2 = (x, y, seed) => {
    let h = (seed ^ Math.imul(x | 0, 0x27d4eb2d) ^ Math.imul(y | 0, 0x165667b1)) >>> 0;
    h ^= h >>> 15;
    h = Math.imul(h, 0x2545f491) >>> 0;
    h ^= h >>> 13;
    h = Math.imul(h, 0x3b7a57e5) >>> 0;
    h ^= h >>> 16;
    return h >>> 0;
};

// mulberry32 — маленький, быстрый, полностью воспроизводимый генератор.
export const makeRng = (seed) => {
    let a = seed >>> 0;
    return () => {
        a = (a + 0x6d2b79f5) >>> 0;
        let t = a;
        t = Math.imul(t ^ (t >>> 15), t | 1);
        t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
};

// Последовательность R2 (Мартин Робертс): плотное, равномерное, но
// неповторяющееся покрытие плоскости без единого обращения к случайности.
// Ею расставляются точки старта мазков — так холст покрывается ровно,
// а не пятнами, как при наивном случайном разбросе.
const G = 1.32471795724474602596; // пластическое число
const A1 = 1 / G;
const A2 = 1 / (G * G);

export const r2Point = (n, offset = 0) => {
    const i = n + offset;
    return [(0.5 + A1 * i) % 1, (0.5 + A2 * i) % 1];
};

// Линейные помощники — вынесены, чтобы не плодить их в каждом файле.
export const clamp = (v, lo, hi) => (v < lo ? lo : v > hi ? hi : v);
export const lerp = (a, b, t) => a + (b - a) * t;
export const mix = (a, b, t) => lerp(a, b, clamp(t, 0, 1));
export const smoothstep = (t) => {
    const x = clamp(t, 0, 1);
    return x * x * (3 - 2 * x);
};
